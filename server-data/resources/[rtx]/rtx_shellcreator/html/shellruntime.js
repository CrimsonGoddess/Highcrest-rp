      "",
      "\tDoScreenFadeIn(400)",
      "",
      "\treturn iddata",
      "end",
      "",
      "local function LeaveShellRTX(iddata, coordsdata, headingdata)",
      "\tDoScreenFadeOut(400)",
      "",
      "\twhile not IsScreenFadedOut() do",
      "\t\tWait(0)",
      "\tend",
      "",
      "\tif coordsdata ~= nil then",
      "\t\tTeleportRTX(vector3(coordsdata.x + 0.0, coordsdata.y + 0.0, coordsdata.z + 0.0), headingdata)",
      "\tend",
      "",
      "\tDespawnShellRTX(iddata)",
      "\tDoScreenFadeIn(400)",
      "end",
      "",
      "local function InsideRTX()",
      "\tlocal coordsdata = GetEntityCoords(PlayerPedId())",
      "",
      "\tfor iddata, instancedata in pairs(INSTANCES) do",
      "\t\tlocal boundsdata = instancedata.shell.bounds",
      "",
      "\t\tif boundsdata == nil then",
      "\t\t\tif #(coordsdata - instancedata.coords) < 30.0 then",
      "\t\t\t\treturn iddata",
      "\t\t\tend",
      "\t\telse",
      "\t\t\tlocal angledata = -math.rad(instancedata.heading)",
      "\t\t\tlocal dx, dy = coordsdata.x - instancedata.coords.x, coordsdata.y - instancedata.coords.y",
      "\t\t\tlocal lx = dx * math.cos(angledata) - dy * math.sin(angledata)",
      "\t\t\tlocal ly = dx * math.sin(angledata) + dy * math.cos(angledata)",
      "\t\t\tlocal lz = coordsdata.z - instancedata.coords.z",
      "",
      "\t\t\tif lx >= boundsdata.min[1] and lx <= boundsdata.max[1] and ly >= boundsdata.min[2] and ly <= boundsdata.max[2] and lz >= boundsdata.min[3] - 1.0 and lz <= boundsdata.max[3] + 1.0 then",
      "\t\t\t\treturn iddata",
      "\t\t\tend",
      "\t\tend",
      "\tend",
      "",
      "\treturn false",
      "end",
      "",
      "local function SetDoorRTX(instancedata, indexdata, opendata)",
      "\tlocal itemdata = instancedata.doors[indexdata]",
      "",
      "\tif itemdata == nil or itemdata.locked then",
      "\t\treturn",
      "\tend",
      "",
      "\titemdata.open = opendata == true",

      "\tif itemdata.busy or not itemdata.alive or itemdata.data.stops[stopdata] == nil then",
      "\t\treturn false",
      "\tend",
      "",
      "\titemdata.busy = true",
      "\titemdata.going = stopdata",
      "",
      "\tif stopdata ~= itemdata.stop then",
      "\t\tLIFT.Lit(itemdata, stopdata)",
      "\tend",
      "",
      "\tCreateThread(function()",
      "\t\tlocal peddata = PlayerPedId()",
      "",
      "\t\tif stopdata ~= itemdata.stop then",
      "\t\t\tif itemdata.gates[itemdata.stop].open > 0.01 then",
      "\t\t\t\tLIFT.Doors(itemdata, itemdata.gates[itemdata.stop], false)",
      "\t\t\tend",
      "",
      "\t\t\tLIFT.WaitGate(itemdata, itemdata.gates[itemdata.stop], 0.0)",
      "\t\t\tWait(250)",
      "\t\t\tLIFT.Play(itemdata, \"lift_start\", 0.0, 0.0, itemdata.z, 1.3, 0.9, true)",
      "\t\t\tWait(150)",
      "\t\t\titemdata.moving = true",
      "\t\t\titemdata.pick = nil",
      "\t\t\tLIFT.Arrows(itemdata, stopdata > itemdata.stop and 1 or -1)",
      "",
      "\t\t\tlocal ridingdata = carrydata == true and itemdata.cabin ~= nil and DoesEntityExist(itemdata.cabin) and LIFT.Inside(itemdata, GetEntityCoords(peddata)) and not IsPedInAnyVehicle(peddata, false)",
      "",
      "\t\t\tif ridingdata then",
      "\t\t\t\tlocal lxdata, lydata, lzdata = LIFT.Local(itemdata, GetEntityCoords(peddata))",
      "",
      "\t\t\t\tNetworkAllowLocalEntityAttachment(peddata, true)",
      "\t\t\t\tAttachEntityToEntity(peddata, itemdata.cabin, 0, lxdata, lydata, lzdata - itemdata.z, 0.0, 0.0, (GetEntityHeading(peddata) - itemdata.heading) % 360.0, false, false, false, false, 2, true)",
      "\t\t\tend",
      "",
      "\t\t\tlocal fromdata = itemdata.z",
      "\t\t\tlocal todata = itemdata.data.stops[stopdata] + 0.0",
      "\t\t\tlocal timedata = math.max(1800.0, math.abs(todata - fromdata) / math.max(0.3, speeddata or 1.5) * 1000.0 + 600.0)",
      "\t\t\tlocal startdata = GetGameTimer()",
      "",
      "\t\t\twhile itemdata.alive do",
      "\t\t\t\tlocal tdata = math.min(1.0, (GetGameTimer() - startdata) / timedata)",
      "",
      "\t\t\t\titemdata.z = fromdata + (todata - fromdata) * (tdata * tdata * (3.0 - 2.0 * tdata))",
      "\t\t\t\tLIFT.Cabin(itemdata)",
      "",
      "\t\t\t\tlocal nearestdata = LIFT.Nearest(itemdata)",
      "",
      "\t\t\t\tif nearestdata ~= itemdata.passed then",
      "\t\t\t\t\tif itemdata.passed ~= nil and nearestdata ~= stopdata and LIFT.Inside(itemdata, GetEntityCoords(peddata)) then",
      "\t\t\t\t\t\tLIFT.Button(itemdata, \"lift_pass\", nil)",
      "\t\t\t\t\tend",
      "",
      "\t\t\t\t\titemdata.passed = nearestdata",
      "\t\t\t\tend",
      "",
      "\t\t\t\tLIFT.Digits(itemdata, nearestdata)",
      "\t\t\t\tLIFT.Cop(itemdata, nearestdata)",
      "\t\t\t\tLIFT.Hum(itemdata, 4.0 * tdata * (1.0 - tdata))",
      "",
      "\t\t\t\tif tdata >= 1.0 then",
      "\t\t\t\t\tbreak",
      "\t\t\t\tend",
      "",
      "\t\t\t\tWait(0)",
      "\t\t\tend",
      "",
      "\t\t\titemdata.stop = stopdata",
      "\t\t\titemdata.moving = false",
      "\t\t\titemdata.passed = nil",
      "\t\t\tLIFT.Hum(itemdata, 0.0)",
      "\t\t\tLIFT.Play(itemdata, \"lift_stop\", 0.0, 0.0, itemdata.z, 1.3, 0.9, true)",
      "",
      "\t\t\tif ridingdata and itemdata.cabin ~= nil and DoesEntityExist(itemdata.cabin) and IsEntityAttachedToEntity(peddata, itemdata.cabin) then",
      "\t\t\t\tlocal coordsdata = GetEntityCoords(peddata)",
      "",
      "\t\t\t\tDetachEntity(peddata, true, false)",
      "\t\t\t\tSetEntityCoordsNoOffset(peddata, coordsdata.x, coordsdata.y, coordsdata.z + 0.03, false, false, false)",
      "\t\t\tend",
      "",
      "\t\t\tLIFT.Digits(itemdata, stopdata)",
      "\t\t\tLIFT.Cop(itemdata, stopdata)",
      "\t\t\tLIFT.Arrows(itemdata, nil)",
      "",
      "\t\t\tWait(350)",
      "\t\t\tLIFT.Play(itemdata, \"lift_ding\", 0.0, -itemdata.layout.hd, itemdata.gates[stopdata].z, 2.4, 0.8, false)",
      "\t\t\tWait(300)",
      "\t\tend",
      "",
      "\t\tLIFT.Lit(itemdata, nil)",
      "\t\tLIFT.Call(itemdata, stopdata, false)",
      "",
      "\t\tif itemdata.alive then",
      "\t\t\tif itemdata.gates[stopdata].open < 0.5 then",
      "\t\t\t\tLIFT.Doors(itemdata, itemdata.gates[stopdata], true)",
      "\t\t\tend",
      "",

      "function LIFT.Mix(atdata, volumedata)",
      "\tlocal camdata = GetFinalRenderedCamCoord()",
      "\tlocal rotdata = GetFinalRenderedCamRot(2)",
      "\tlocal maxdata = LIFT.sound.distance or 24.0",
      "\tlocal distancedata = #(camdata - atdata)",
      "",
      "\tif distancedata >= maxdata then",
      "\t\treturn 0.0, 0.0",
      "\tend",
      "",
      "\tlocal falloffdata = 1.0 - distancedata / maxdata",
      "\tlocal yawdata = math.rad(rotdata.z)",
      "\tlocal dxdata, dydata = atdata.x - camdata.x, atdata.y - camdata.y",
      "\tlocal lengthdata = math.sqrt(dxdata * dxdata + dydata * dydata)",
      "\tlocal pandata = 0.0",
      "",
      "\tif lengthdata > 0.25 then",
      "\t\tpandata = math.max(-1.0, math.min(1.0, (dxdata * math.cos(yawdata) + dydata * math.sin(yawdata)) / lengthdata)) * 0.75 * math.min(1.0, lengthdata / 1.5)",
      "\tend",
      "",
      "\treturn volumedata * falloffdata * falloffdata * (LIFT.sound.volume or 0.8), pandata",
      "end",
